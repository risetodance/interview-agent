    private int docCount() { return DOCS.size(); }
    private String fullDoc(int d) { return String.join("\n\n", paras(d)); }
    private String[] paras(int d) { return (String[]) DOCS.get(d)[0]; }
    private String keywords(int d) { return (String) DOCS.get(d)[1]; }
    private String[] abKeywords(int d) { String[] p = keywords(d).split("\\|"); return new String[]{p[0], p[1]}; }
    private String[] crossKeywords(int d) { String[] p = keywords(d).split("\\|"); return new String[]{p[2], p[3]}; }


    /** 三种策略各自构建回答上下文 */
    private String[] buildContexts(JdbcTemplate jt, String vecLiteral, int targetDoc) {
        String qv = vecLiteral;
        // 0 普通RAG：全局 fixed top1
        String fixedTop1 = jt.queryForObject(
                "SELECT content FROM vector_store WHERE metadata->>'strategy' = 'fixed' ORDER BY embedding <=> ?::vector LIMIT 1", String.class, qv);
        // 1 窗口拼接：全局 fixed top1 的 docId/idx，取 idx-1..idx+1 按 idx 排序拼接
        Map<String, Object> top1Meta = jt.queryForMap(
                "SELECT metadata->>'docId' AS doc, (metadata->>'idx')::int AS idx FROM vector_store WHERE metadata->>'strategy' = 'fixed' ORDER BY embedding <=> ?::vector LIMIT 1", qv);
        List<String> window = jt.queryForList(
                "SELECT content FROM vector_store WHERE metadata->>'strategy' = 'fixed' AND metadata->>'docId' = '" + top1Meta.get("doc") + "' " +
                        "AND (metadata->>'idx')::int BETWEEN " + (((int) top1Meta.get("idx")) - 1) + " AND " + (((int) top1Meta.get("idx")) + 1) +
                        " ORDER BY (metadata->>'idx')::int", String.class);
        String windowCtx = String.join("", window);
        // 2 语义PC：全局 child top1 命中段落后回链其 parent（段0-2=parent0 / 段3-5=parent1）
        Map<String, Object> childMeta = jt.queryForMap(
                "SELECT metadata->>'docId' AS doc, (metadata->>'idx')::int AS idx, content FROM vector_store WHERE metadata->>'strategy' = 'child' ORDER BY embedding <=> ?::vector LIMIT 1", qv);
        int cDoc = Integer.parseInt((String) childMeta.get("doc"));
        int cIdx = (int) childMeta.get("idx");
        // 语义 parent 分组：段 0-5 → parent0（A段2、B段5 同 parent 且相距超窗口），段 6-7 → parent1（C）
        int parentStart = cIdx < 6 ? 0 : 6;
        int parentEnd = Math.min(parentStart + 6, paras(cDoc).length);
        StringBuilder pcCtx = new StringBuilder();
        System.out.printf("[EVAL]   PC回链: doc=%d childIdx=%d parent=[%d,%d) ", cDoc, cIdx, parentStart, parentEnd);
        for (int i = parentStart; i < parentEnd; i++) {
            if (i > parentStart) pcCtx.append("\n\n");
            pcCtx.append(paras(cDoc)[i]);
        }
        System.out.printf("ctxLen=%d%n", pcCtx.length());
        return new String[]{fixedTop1 == null ? "" : fixedTop1, windowCtx, pcCtx.toString()};
    }

    private String answer(ChatClient chat, String query, String context) {
        try {
            return chat.prompt()
                    .system("你是知识库问答助手。仅根据提供的资料回答问题，资料中没有的信息不要编造，直接说明资料中未提及。")
                    .user("资料：\n" + context + "\n\n问题：" + query)
                    .call().content();
        } catch (Exception e) { return ""; }
    }

    /** 每题两个要点各 0.5 分 */
    private double score(String answer, String kw1, String kw2) {
        if (answer == null || answer.isBlank()) return 0;
        double s = 0;
        if (answer.contains(kw1)) s += 0.5;
        if (answer.contains(kw2)) s += 0.5;
        return s;
    }

    /** 答案数值编造率：答案里的数字不在上下文中出现的比例（precision 的反面） */
    private double fabricationRate(String answer, String context) {
        if (answer == null || answer.isBlank()) return 0;
        java.util.regex.Matcher m = java.util.regex.Pattern.compile("\\d+(?:\\.\\d+)?%?").matcher(answer);
        int total = 0, fab = 0;
        while (m.find()) {
            String num = m.group();
            total++;
            if (!context.contains(num)) fab++;
        }
        return total == 0 ? 0 : (double) fab / total;
    }

    private String toVectorLiteral(float[] vec) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < vec.length; i++) { if (i > 0) sb.append(','); sb.append(vec[i]); }
        return sb.append(']').toString();
    }
